class _Message:
    def __init__(self, content: str) -> None:
        self.content = content


class _Choice:
    def __init__(self, content: str, finish_reason: str | None = None) -> None:
        self.message = _Message(content)
        self.finish_reason = finish_reason


class _Usage:
    def __init__(self, prompt: int, completion: int) -> None:
        self.prompt_tokens = prompt
        self.completion_tokens = completion


class _Response:
    def __init__(
        self,
        content: str,
        *,
        prompt: int = 1000,
        completion: int = 200,
        finish_reason: str | None = None,
    ) -> None:
        self.choices = [_Choice(content, finish_reason)]
        self.usage = _Usage(prompt, completion)


def _segments_json(segments: list[dict[str, Any]]) -> str:
    return json.dumps({"segments": segments})


_GOOD_JSON = _segments_json(
    [
        {"start": 0.0, "end": 3.5, "text": "Hello and welcome to the talk."},
        {"start": 3.5, "end": 8.0, "text": "Today we discuss audio transcription."},
        {"start": 65.0, "end": 70.0, "text": "An hour-ish in we wrap up."},
    ]
)


def _mock_litellm(response: Any | list[Any]) -> AsyncMock:
    """Build a stand-in litellm module whose acompletion returns ``response``.

    If ``response`` is a list, successive calls pop from it (for retry tests).
    """
    mod = AsyncMock()
    if isinstance(response, list):
        mod.acompletion = AsyncMock(side_effect=response)
    else:
        mod.acompletion = AsyncMock(return_value=response)
    return mod


