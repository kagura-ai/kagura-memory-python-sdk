def _make_client() -> Any:
    from kagura_memory.client import KaguraClient

    client = KaguraClient(api_key="test", mcp_url="https://test.com/mcp")
    client._session_id = "test-session"
    return client


class _FakeProvider:
    name = "fake"
    default_text_model = "fake/text"
    default_vision_model: str | None = None
    text_model = "fake/text"
    vision_model: str | None = None

    async def summarize(self, text: str, *, max_tokens: int) -> str:
        return f"[summary len={len(text)}]"

    async def summarize_overview(self, section_summaries: list[str], *, max_tokens: int) -> str:
        return f"[overview {len(section_summaries)}]"

    async def describe_image(self, image_bytes: bytes, mime: str) -> str:
        return "[image]"

    def count_tokens(self, text: str, *, for_vision: bool = False) -> int:
        return max(1, len(text) // 4)


@pytest.mark.asyncio
async def test_ingest_routes_mp3_to_audio_path(tmp_path: Path) -> None:
    from kagura_memory.ingest import FileIngestor

    audio_file = tmp_path / "talk.mp3"
    audio_file.write_bytes(b"ID3\x04\x00fakeaudiobytes")

    client = _make_client()
    ingestor = FileIngestor(client=client, text_provider=_FakeProvider(), vision_provider=None)

    counter = {"n": 0}
    captured: list[dict[str, Any]] = []

    async def capture_remember(*, context_id: str, **kwargs: Any) -> dict[str, Any]:
        captured.append({"context_id": context_id, **kwargs})
        counter["n"] += 1
        return {"memory_id": f"mem-{counter['n']}"}

    mod = _mock_litellm(_Response(_GOOD_JSON, prompt=5000, completion=400))
    with (
        patch.object(_audio, "_load_litellm", return_value=mod),
        patch.object(client, "remember", side_effect=capture_remember),
    ):
        result = await ingestor.ingest(str(audio_file), context_id="ctx-uuid")

    assert result.success is True
    assert result.overview_id == "mem-1"
    assert len(result.section_ids) == 3
    # format label routed as audio; cost carries the provider token usage.
    assert captured[0]["details"]["format"] == "audio"
    assert result.cost.prompt_tokens == 5000
    assert result.cost.completion_tokens == 400
    assert result.cost.is_estimate is False

    await client.close()


