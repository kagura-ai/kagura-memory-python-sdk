@pytest.mark.parametrize(
    ("uri", "expected"),
    [
        ("/tmp/talk.mp3", "audio/mpeg"),
        ("/tmp/talk.wav", "audio/wav"),
        ("/tmp/talk.m4a", "audio/mp4"),
        ("/tmp/clip.mp4", "video/mp4"),
        ("https://x.com/a/talk.MP3?token=abc", "audio/mpeg"),
        ("/tmp/report.pdf", None),
        ("/tmp/notes.txt", None),
    ],
)
def test_detect_audio_mime_by_suffix(uri: str, expected: str | None) -> None:
    assert detect_audio_mime(source_uri=uri, body=b"") == expected


def test_detect_audio_mime_by_magic_bytes_mp3_id3() -> None:
    assert detect_audio_mime(source_uri="/tmp/noext", body=b"ID3\x04\x00") == "audio/mpeg"


def test_detect_audio_mime_by_magic_bytes_mp3_sync() -> None:
    assert detect_audio_mime(source_uri="/tmp/noext", body=b"\xff\xfb\x90\x00") == "audio/mpeg"


def test_detect_audio_mime_by_magic_bytes_wav() -> None:
    body = b"RIFF\x24\x08\x00\x00WAVEfmt "
    assert detect_audio_mime(source_uri="/tmp/noext", body=body) == "audio/wav"


def test_detect_audio_mime_by_magic_bytes_m4a() -> None:
    body = b"\x00\x00\x00\x20ftypM4A \x00\x00\x00\x00"
    assert detect_audio_mime(source_uri="/tmp/noext", body=body) == "audio/mp4"


def test_detect_audio_mime_by_magic_bytes_mp4() -> None:
    body = b"\x00\x00\x00\x18ftypmp42\x00\x00\x00\x00"
    assert detect_audio_mime(source_uri="/tmp/noext", body=body) == "video/mp4"


def test_detect_audio_mime_non_audio_returns_none() -> None:
    assert detect_audio_mime(source_uri="/tmp/x", body=b"%PDF-1.7 not audio") is None


def test_detect_audio_mime_by_content_type_when_suffix_and_magic_miss() -> None:
    # No audio suffix and non-audio magic bytes, but a registered audio
    # Content-Type — the Content-Type must win (server is authoritative).
    assert (
        detect_audio_mime(
            source_uri="https://cdn.example/stream?id=42",
            body=b"not-a-recognized-magic-prefix",
            content_type="audio/mpeg",
        )
        == "audio/mpeg"
    )


def test_detect_audio_mime_content_type_wins_over_non_audio_suffix() -> None:
    # A registered audio Content-Type takes precedence over a non-audio
    # filename suffix (e.g. an extension-less download endpoint named *.bin).
    assert (
        detect_audio_mime(
            source_uri="https://cdn.example/download.bin",
            body=b"",
            content_type="audio/mp4; codecs=mp4a.40.2",
        )
        == "audio/mp4"
    )


def test_detect_audio_mime_content_type_video_recognized() -> None:
    assert (
        detect_audio_mime(source_uri="/tmp/clip", body=b"", content_type="video/mp4") == "video/mp4"
    )


def test_detect_audio_mime_generic_content_type_falls_back_to_suffix() -> None:
    # A GENERIC Content-Type (octet-stream) is "I don't know", so suffix
    # detection still applies (a real .mp3 mislabeled by the server).
    assert (
        detect_audio_mime(
            source_uri="/tmp/talk.mp3",
            body=b"",
            content_type="application/octet-stream",
        )
        == "audio/mpeg"
    )


def test_detect_audio_mime_concrete_non_audio_content_type_blocks_suffix() -> None:
    # A CONCRETE non-audio Content-Type (e.g. text/html for a login/redirect
    # page served at a .mp3 URL) is authoritative — it must NOT be audio-routed
    # on the misleading suffix, so the bytes never reach Gemini.
    assert (
        detect_audio_mime(
            source_uri="https://evil.example/login.mp3",
            body=b"<!doctype html>",
            content_type="text/html; charset=utf-8",
        )
        is None
    )


def test_detect_audio_mime_audio_alias_content_type_falls_back_to_suffix() -> None:
    # An unrecognized audio/* alias (audio/mp3, audio/wave) is NOT "something
    # else" — it must fall through to suffix/magic so a real MP3/WAV routes.
    assert (
        detect_audio_mime(source_uri="/tmp/talk.mp3", body=b"", content_type="audio/mp3")
        == "audio/mpeg"
    )
    assert (
        detect_audio_mime(source_uri="/tmp/talk.wav", body=b"", content_type="audio/wave")
        == "audio/wav"
    )


def test_detect_audio_mime_rejects_non_av_ftyp_brands() -> None:
    # AVIF / HEIC images are ISO-BMFF with an "ftyp" box too — they must NOT be
    # routed to transcription. Only known MP4/M4A brands match.
    avif = b"\x00\x00\x00\x20ftypavif\x00\x00\x00\x00"
    heic = b"\x00\x00\x00\x18ftypheic\x00\x00\x00\x00"
    assert detect_audio_mime(source_uri="/tmp/img", body=avif) is None
    assert detect_audio_mime(source_uri="/tmp/img", body=heic) is None


def test_is_audio_mime() -> None:
    assert is_audio_mime("audio/mpeg") is True
    assert is_audio_mime("video/mp4") is True
    assert is_audio_mime("audio/mpeg; codecs=x".replace("mpeg", "mpeg")) is True
    assert is_audio_mime("application/pdf") is False
    assert is_audio_mime(None) is False


def test_audio_format_label() -> None:
    assert audio_format_label("audio/mpeg") == "audio"
    assert audio_format_label("video/mp4") == "video"


