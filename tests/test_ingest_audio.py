@pytest.mark.asyncio
async def test_transcribe_happy_path_builds_time_windowed_sections() -> None:
    mod = _mock_litellm(_Response(_GOOD_JSON, prompt=4096, completion=300))
    with patch.object(_audio, "_load_litellm", return_value=mod):
        content, usage = await transcribe_audio(
            b"\x00fakeaudio", mime="audio/mpeg", source_uri="/data/talk.mp3"
        )

    assert content.title == "talk.mp3"
    assert content.page_count is None
    assert len(content.sections) == 3
    # Headings are mm:ss timestamps; the > 1h-ish one stays mm:ss until 3600s.
    assert content.sections[0].heading == "[00:00]"
    assert content.sections[0].anchor == "00:00-00:03"
    assert content.sections[0].body_text == "Hello and welcome to the talk."
    assert content.sections[1].heading == "[00:03]"
    assert content.sections[2].heading == "[01:05]"
    assert content.sections[2].anchor == "01:05-01:10"
    # Provider-reported usage threaded out for CostBreakdown.
    assert usage.prompt_tokens == 4096
    assert usage.completion_tokens == 300

    # The audio bytes were attached inline as base64 data-url.
    call = mod.acompletion.call_args
    messages = call.kwargs["messages"]
    parts = messages[1]["content"]
    data_url = next(p["image_url"]["url"] for p in parts if p["type"] == "image_url")
    assert data_url.startswith("data:audio/mpeg;base64,")
    assert base64.b64encode(b"\x00fakeaudio").decode() in data_url
    assert call.kwargs["response_format"] == {"type": "json_object"}


