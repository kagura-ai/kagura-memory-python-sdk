@pytest.mark.parametrize(
    ("uri", "expected"),
    [
        ("/tmp/talk.mp3", "audio/mpeg"),
        ("/tmp/talk.wav", "audio/wav"),
        ("/tmp/talk.m4a", "audio/mp4"),
        ("/tmp/clip.mp4", "video/mp4"),
        ("https://x.com/a/talk.MP3?token=abc", "audio/mpeg"),
        ("/tmp/report.pdf", None),
        ("/tmp/notes.txt", None),
    ],
)
def test_detect_audio_mime_by_suffix(uri: str, expected: str | None) -> None:
    assert detect_audio_mime(source_uri=uri, body=b"") == expected


def test_detect_audio_mime_by_magic_bytes_mp3_id3() -> None:
    assert detect_audio_mime(source_uri="/tmp/noext", body=b"ID3\x04\x00") == "audio/mpeg"


def test_detect_audio_mime_by_magic_bytes_mp3_sync() -> None:
    assert detect_audio_mime(source_uri="/tmp/noext", body=b"\xff\xfb\x90\x00") == "audio/mpeg"


def test_detect_audio_mime_by_magic_bytes_wav() -> None:
    body = b"RIFF\x24\x08\x00\x00WAVEfmt "
    assert detect_audio_mime(source_uri="/tmp/noext", body=body) == "audio/wav"


def test_detect_audio_mime_by_magic_bytes_m4a() -> None:
    body = b"\x00\x00\x00\x20ftypM4A \x00\x00\x00\x00"
    assert detect_audio_mime(source_uri="/tmp/noext", body=body) == "audio/mp4"


def test_detect_audio_mime_by_magic_bytes_mp4() -> None:
    body = b"\x00\x00\x00\x18ftypmp42\x00\x00\x00\x00"
    assert detect_audio_mime(source_uri="/tmp/noext", body=body) == "video/mp4"


def test_detect_audio_mime_non_audio_returns_none() -> None:
    assert detect_audio_mime(source_uri="/tmp/x", body=b"%PDF-1.7 not audio") is None


def test_is_audio_mime() -> None:
    assert is_audio_mime("audio/mpeg") is True
    assert is_audio_mime("video/mp4") is True
    assert is_audio_mime("audio/mpeg; codecs=x".replace("mpeg", "mpeg")) is True
    assert is_audio_mime("application/pdf") is False
    assert is_audio_mime(None) is False


def test_audio_format_label() -> None:
    assert audio_format_label("audio/mpeg") == "audio"
    assert audio_format_label("video/mp4") == "video"


